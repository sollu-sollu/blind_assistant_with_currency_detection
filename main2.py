# ──────────────────────────────────────────────────────────────────
#  SECTION 1 — Async TTS Engine
# ──────────────────────────────────────────────────────────────────

class TTSSpeaker:
    """
    Runs pyttsx3 in its own thread with a queue.
    This ensures the vision loop is NEVER blocked by speaking.
    Deduplicates messages within the cooldown window.
    """

    def __init__(self, rate: int = 145, cooldown: float = 2.5):
        self._queue     = queue.Queue(maxsize=5)
        self._last_msg  = {}
        self._cooldown  = cooldown
        self._rate      = rate
        t = threading.Thread(target=self._run, daemon=True)
        t.start()

    def say(self, text: str):
        now = time.time()
        if now - self._last_msg.get(text, 0) < self._cooldown:
            return  # Skip duplicate within cooldown window
        self._last_msg[text] = now
        try:
            self._queue.put_nowait(text)
        except queue.Full:
            pass  # Drop if queue is full — keeps real-time

    def _run(self):
        # pyttsx3 MUST be initialized in the thread where it speaks on Windows!
        # Otherwise SAPI5 fails silently.
        import pyttsx3
        engine = pyttsx3.init()
        engine.setProperty('rate', self._rate)
        
        while True:
            text = self._queue.get()
            try:
                engine.say(text)
                engine.runAndWait()
            except Exception as e:
                print(f"TTS Error: {e}")


