# ──────────────────────────────────────────────────────────────────
#  AUTO FACE REGISTRATION
#  Runs at every startup. If new photos added to known_faces/, it
#  automatically re-encodes and updates face_encodings.pkl.
# ──────────────────────────────────────────────────────────────────

KNOWN_FACES_DIR = "known_faces"
ENCODINGS_FILE  = "face_encodings.pkl"


def _get_latest_photo_mtime(folder):
    """Return the most recent mtime of any image file inside known_faces/."""
    latest = 0.0
    exts   = {'.jpg', '.jpeg', '.png', '.bmp'}
    for root, _, files in os.walk(folder):
        for f in files:
            if os.path.splitext(f)[1].lower() in exts:
                t = os.path.getmtime(os.path.join(root, f))
                if t > latest:
                    latest = t
    return latest


def auto_register_faces():
    """
    Called automatically every time main2.py starts.
    Compares modification times:
      - If any photo in known_faces/ is NEWER than face_encodings.pkl
        → re-encode all faces and overwrite the .pkl.
      - If .pkl is already up to date → skip (fast startup).
    Just drop new photos into known_faces/PersonName/ and restart.
    """
    print("[FaceReg] Checking for new faces...")

    if not FACE_RECOGNITION_AVAILABLE:
        print("[FaceReg] face_recognition not installed — skipping.")
        return

    if not os.path.isdir(KNOWN_FACES_DIR):
        os.makedirs(KNOWN_FACES_DIR)
        print(f"[FaceReg] Created '{KNOWN_FACES_DIR}/' — add sub-folders with photos.")
        print(f"           Example: known_faces/Rajendran/photo1.jpg")
        return

    # Compare timestamps
    photo_mtime = _get_latest_photo_mtime(KNOWN_FACES_DIR)
    if photo_mtime == 0.0:
        print("[FaceReg] No photos found in known_faces/. Skipping.")
        return

    pkl_mtime = os.path.getmtime(ENCODINGS_FILE) if os.path.exists(ENCODINGS_FILE) else 0.0
    if pkl_mtime >= photo_mtime:
        print("[FaceReg] Encodings are up to date — skipping re-registration.")
        return

    # ── Re-encode all faces ─────────────────────────────────
    print("[FaceReg] New photos detected — building face encodings...")
    known_encodings = []
    known_names     = []
    exts            = {'.jpg', '.jpeg', '.png', '.bmp'}

    persons = sorted([
        d for d in os.listdir(KNOWN_FACES_DIR)
        if os.path.isdir(os.path.join(KNOWN_FACES_DIR, d))
    ])

    for person in persons:
        person_dir = os.path.join(KNOWN_FACES_DIR, person)
        photos     = [f for f in os.listdir(person_dir)
                      if os.path.splitext(f)[1].lower() in exts]
        added = 0
        for photo in photos:
            try:
                img  = face_recognition.load_image_file(os.path.join(person_dir, photo))
                encs = face_recognition.face_encodings(img)
                if not encs:
                    print(f"[FaceReg]   ⚠ No face in '{photo}'. Skipping.")
                    continue
                known_encodings.append(encs[0])
                known_names.append(person)
                added += 1
            except Exception as e:
                print(f"[FaceReg]   ⚠ Error '{photo}': {e}")
        print(f"[FaceReg]   ✓ {person}: {added} photo(s) encoded.")

    if known_encodings:
        with open(ENCODINGS_FILE, 'wb') as f:
            pickle.dump({"encodings": known_encodings, "names": known_names}, f)
        print(f"[FaceReg] ✅ {len(known_encodings)} encoding(s) saved → '{ENCODINGS_FILE}'")
    else:
        print("[FaceReg] ⚠ No valid faces found. Check photo quality.")

