# Labels from the general YOLO model that are useful for the blind
RELEVANT_OBJECTS = {
    "person", "car", "truck", "bus", "bicycle", "motorcycle",
    "chair", "door", "stairs", "bottle", "cup", "cell phone",
    "laptop", "tv", "book", "bag", "umbrella", "cat", "dog",
}


def draw_label(frame, text, x1, y1, color=(0, 255, 0)):
    cv2.rectangle(frame, (x1 - 1, y1 - 22), (x1 + len(text) * 9, y1), color, -1)
    cv2.putText(frame, text, (x1, y1 - 5),
                cv2.FONT_HERSHEY_SIMPLEX, 0.55, (0, 0, 0), 1, cv2.LINE_AA)


def main():
    print("\n" + "=" * 55)
    print("  BLIND ASSISTANT STARTING")
    print("=" * 55 + "\n")

    tts = TTSSpeaker(rate=CONFIG["SPEECH_RATE"], cooldown=CONFIG["TTS_COOLDOWN_S"])
    tts.say("Blind Assistant starting. Please wait.")

    # ── Models ──────────────────────────────────────────────────
    print("Loading YOLO26n general model...")
    general_model = YOLO(CONFIG["YOLO_GENERAL_MODEL"])

    # Auto-detect currency model: prefer NCNN (faster on Pi), fall back to .pt
    currency_model = None
    ncnn_path = CONFIG["YOLO_CURRENCY_MODEL_NCNN"]
    pt_path   = CONFIG["YOLO_CURRENCY_MODEL_PT"]

    if os.path.isdir(ncnn_path):
        print(f"Loading currency model (NCNN — fastest on Pi): {ncnn_path}")
        currency_model = YOLO(ncnn_path)
    elif os.path.exists(pt_path):
        print(f"Loading currency model (PyTorch): {pt_path}")
        currency_model = YOLO(pt_path)
    else:
        print("⚠ Currency model not found. Copy 'currency_yolo26n.pt' or")
        print("  'currency_yolo26n_ncnn_model/' folder to this directory.")
        print("  Object detection and face recognition will still work.")

    # ── Step 0: Auto-register faces before loading engine ────────
    # Detects new photos in known_faces/ and rebuilds face_encodings.pkl.
    # This happens automatically every time main2.py starts.
    auto_register_faces()

    # ── Face Engine ─────────────────────────────────────────────
    face_engine = FaceEngine(
        encodings_file=ENCODINGS_FILE,
        tolerance=CONFIG["FACE_TOLERANCE"]
    )

    # ── Camera ──────────────────────────────────────────────────
    cam = CameraStream(
        index  = CONFIG["CAMERA_INDEX"],
        width  = CONFIG["FRAME_WIDTH"],
        height = CONFIG["FRAME_HEIGHT"]
    )
    time.sleep(1.5)  # Let camera warm up

    # ── Sensors ──────────────────────────────────────────────────
    # Safe on Windows: GPIO_AVAILABLE=False so no pins are touched,
    # dist_cm stays 999 and ir_triggered stays False.
    sensors = SensorMonitor(tts, CONFIG)

    tts.say("System ready.")
    print("System ready. Press Q to quit.\n")

    # ── Display window setup ───────────────────────────────────
    WIN_NAME   = "Blind Assistant - Detection View"
    DISP_SCALE = 2          # Scale camera 320×240 → 960×720
    PANEL_W    = 380        # Width of right-side info panel
    DISP_H     = CONFIG["FRAME_HEIGHT"] * DISP_SCALE   # 720
    DISP_W     = CONFIG["FRAME_WIDTH"]  * DISP_SCALE   # 960
    TOTAL_W    = DISP_W + PANEL_W                       # 1340

    cv2.namedWindow(WIN_NAME, cv2.WINDOW_NORMAL)
    cv2.resizeWindow(WIN_NAME, TOTAL_W, DISP_H)

    frame_count          = 0
    fps_timer            = time.time()
    display_fps          = 0
    FACE_CHECK_EVERY     = CONFIG["FACE_CHECK_EVERY"]
    CURRENCY_CHECK_EVERY = CONFIG["CURRENCY_CHECK_EVERY"]

    while True:
        frame = cam.read()
        if frame is None:
            time.sleep(0.01)
            continue

        frame_count += 1

        # ── FPS Calculation ───────────────────────────────────
        if frame_count % 30 == 0:
            elapsed     = time.time() - fps_timer
            display_fps = 30 / elapsed if elapsed > 0 else 0
            fps_timer   = time.time()

        # ── STEP 1: YOLO26n General Object Detection ──────────
        results = general_model(
            frame,
            conf    = CONFIG["YOLO_CONF"],
            imgsz   = CONFIG["YOLO_IMGSZ"],
            verbose = False,
        )

        detected_currency_region = None
        person_detected          = False
        object_spoken            = False

        for r in results:
            for box in r.boxes:
                cls_id  = int(box.cls[0])
                label   = general_model.names[cls_id]
                conf    = float(box.conf[0])
                x1, y1, x2, y2 = map(int, box.xyxy[0])

                # Draw bounding box
                cv2.rectangle(frame, (x1, y1), (x2, y2), (0, 220, 0), 1)
                draw_label(frame, f"{label} {conf:.0%}", x1, y1, (0, 220, 0))

                # Trigger voice for relevant objects
                if label in RELEVANT_OBJECTS:
                    if label == "person":
                        person_detected = True
                        # Face recognition handled later
                    else:
                        ultrasonic = getattr(sensors, '_ultrasonic', None)
                        if GPIO_AVAILABLE and ultrasonic and sensors.dist_cm < 900:
                            dist_m = sensors.dist_cm / 100.0
                            tts.say(f"{label} in {dist_m:.1f} meter")
                        else:
                            tts.say(f"{label} ahead")
                        object_spoken = True

                # Flag currency region for the currency model
                if label in ("book", "paper") and currency_model:
                    detected_currency_region = (x1, y1, x2, y2)

        # Fallback: if no specific object matched but obstacle is very close (<5m)
        ultrasonic = getattr(sensors, '_ultrasonic', None)
        if not object_spoken and not person_detected:
            if GPIO_AVAILABLE and ultrasonic and sensors.dist_cm < 500:
                tts.say("There is an object in front of you.")

        # ── STEP 4: Build display canvas ───────────────────────

        # Scale up the camera frame for viewing (YOLO still ran on small frame)
        big_frame = cv2.resize(frame, (DISP_W, DISP_H), interpolation=cv2.INTER_LINEAR)

        # Create dark side panel
        panel = np.zeros((DISP_H, PANEL_W, 3), dtype=np.uint8)
        panel[:] = (28, 28, 28)  # dark background

        # ── Panel header ──────────────────────────────────────
        cv2.rectangle(panel, (0, 0), (PANEL_W, 50), (45, 45, 45), -1)
        cv2.putText(panel, "BLIND ASSISTANT", (12, 22),
                    cv2.FONT_HERSHEY_DUPLEX, 0.65, (100, 255, 100), 1, cv2.LINE_AA)
        cv2.putText(panel, f"FPS: {display_fps:.1f}    Q = Quit", (12, 44),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.50, (160, 160, 160), 1, cv2.LINE_AA)
        cv2.line(panel, (0, 50), (PANEL_W, 50), (70, 70, 70), 1)

        y = 70  # cursor y for panel text

        def panel_section(title, color=(120, 220, 255)):
            """Draw a section title bar."""
            nonlocal y
            cv2.rectangle(panel, (0, y), (PANEL_W, y + 26), (50, 50, 50), -1)
            cv2.putText(panel, f"  {title}", (8, y + 18),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.55, color, 1, cv2.LINE_AA)
            y += 30

        def panel_row(label, value, val_color=(255, 255, 255)):
            """Draw one data row: label on left, value on right."""
            nonlocal y
            cv2.putText(panel, label, (12, y + 15),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.50, (160, 160, 160), 1, cv2.LINE_AA)
            cv2.putText(panel, str(value), (160, y + 15),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.55, val_color, 1, cv2.LINE_AA)
            y += 26

        # ── SENSORS section ─────────────────────────────────
        panel_section("SENSORS", (120, 220, 255))
        if GPIO_AVAILABLE and sensors._ultrasonic:
            dist_val   = f"{sensors.dist_cm:.0f} cm"
            dist_color = (0, 80, 255) if sensors.dist_cm < CONFIG["OBSTACLE_WARN_CM"] else (80, 255, 80)
            panel_row("Ultrasonic", dist_val, dist_color)
            ir_val   = "TRIGGERED" if sensors.ir_triggered else "Clear"
            ir_color = (0, 80, 255) if sensors.ir_triggered else (80, 255, 80)
            panel_row("IR Sensor", ir_val, ir_color)
        else:
            panel_row("Status", "Offline (PC mode)", (120, 120, 120))
        y += 6

        # ── OBJECTS section ─────────────────────────────────
        panel_section("DETECTED OBJECTS", (100, 255, 160))
        obj_found = False
        for r in results:
            for box in r.boxes:
                lbl  = general_model.names[int(box.cls[0])]
                conf = float(box.conf[0])
                panel_row(lbl.capitalize(), f"{conf:.0%}", (255, 255, 255))
                obj_found = True
        if not obj_found:
            panel_row("None", "", (80, 80, 80))
        y += 6

        # ── CURRENCY section ───────────────────────────────
        panel_section("CURRENCY", (0, 200, 255))
        if currency_model:
            curr_results = currency_model(
                frame, conf=0.60, imgsz=CONFIG["YOLO_IMGSZ"], verbose=False
            ) if frame_count % CURRENCY_CHECK_EVERY == 0 else []
            curr_found = False
            for r in curr_results:
                for box in r.boxes:
                    raw_lbl = currency_model.names[int(box.cls[0])]
                    spoken  = CURRENCY_LABELS.get(raw_lbl, raw_lbl)
                    conf    = float(box.conf[0])
                    panel_row("Note", f"Rs {spoken}  {conf:.0%}", (0, 220, 255))
                    # Draw on big frame too
                    x1s = int(box.xyxy[0][0]) * DISP_SCALE
                    y1s = int(box.xyxy[0][1]) * DISP_SCALE
                    x2s = int(box.xyxy[0][2]) * DISP_SCALE
                    y2s = int(box.xyxy[0][3]) * DISP_SCALE
                    cv2.rectangle(big_frame, (x1s, y1s), (x2s, y2s), (0, 215, 255), 2)
                    cv2.putText(big_frame, f"Rs {spoken}", (x1s, y1s - 8),
                                cv2.FONT_HERSHEY_SIMPLEX, 0.75, (0, 215, 255), 2)
                    tts.say(f"{spoken}.")
                    curr_found = True
            if not curr_found:
                panel_row("None", "", (80, 80, 80))
        else:
            panel_row("Model", "Not loaded", (80, 80, 80))
        y += 6

        # ── FACES section ──────────────────────────────────
        panel_section("FACES", (255, 120, 60))
        if frame_count % FACE_CHECK_EVERY == 0 and person_detected:
            faces = face_engine.process(frame)
            face_found = False
            for (name, x, y_f, w_f, h_f) in faces:
                color = (255, 80, 0) if name != "Unknown" else (80, 80, 255)
                # Scale box to big frame
                cv2.rectangle(big_frame,
                              (x * DISP_SCALE, y_f * DISP_SCALE),
                              ((x + w_f) * DISP_SCALE, (y_f + h_f) * DISP_SCALE), color, 2)
                cv2.putText(big_frame, name,
                            (x * DISP_SCALE, y_f * DISP_SCALE - 10),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.80, color, 2)
                face_color = (80, 80, 255) if name == "Unknown" else (255, 180, 80)
                panel_row("Person", name, face_color)
                if name == "Unknown":
                    tts.say("It is an unknown person.")
                else:
                    tts.say(f"It is {name}.")
                face_found = True
            if not face_found:
                panel_row("None", "", (80, 80, 80))
        else:
            panel_row("", "Scanning...", (80, 80, 80))
        y += 6

        # ── Legend at panel bottom ───────────────────────────
        legend_y = DISP_H - 70
        cv2.line(panel, (0, legend_y), (PANEL_W, legend_y), (60, 60, 60), 1)
        for i, (text, col) in enumerate([
            ("Green boxes = Objects",   (80, 255, 80)),
            ("Yellow boxes = Currency", (0, 215, 255)),
            ("Blue/Orange = Face",      (255, 160, 80)),
        ]):
            cv2.putText(panel, text, (12, legend_y + 18 + i * 20),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.42, col, 1, cv2.LINE_AA)

        # ── Scale up bounding boxes on big_frame ───────────────
        for r in results:
            for box in r.boxes:
                x1, y1, x2, y2 = map(int, box.xyxy[0])
                lbl  = general_model.names[int(box.cls[0])]
                conf = float(box.conf[0])
                cv2.rectangle(big_frame,
                              (x1 * DISP_SCALE, y1 * DISP_SCALE),
                              (x2 * DISP_SCALE, y2 * DISP_SCALE), (0, 220, 0), 2)
                cv2.putText(big_frame, f"{lbl} {conf:.0%}",
                            (x1 * DISP_SCALE, max(y1 * DISP_SCALE - 8, 20)),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.68, (0, 255, 0), 2, cv2.LINE_AA)

        # ── Stitch frame + panel side by side ─────────────────
        canvas = np.hstack([big_frame, panel])

        # ── STEP 5: Show window ───────────────────────────────
        cv2.imshow(WIN_NAME, canvas)

        if cv2.waitKey(1) & 0xFF == ord('q'):
            break


