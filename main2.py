class CameraStream:
    """
    Runs capture in a background thread to prevent frame lag.
    Always provides the latest frame.
    """

    def __init__(self, index: int, width: int, height: int):
        import platform
        # Use V4L2 on Linux (Raspberry Pi), default backend on Windows/Mac
        if platform.system() == "Linux":
            self._cap = cv2.VideoCapture(index, cv2.CAP_V4L2)
        else:
            self._cap = cv2.VideoCapture(index)  # Windows/Mac default
        self._cap.set(cv2.CAP_PROP_FRAME_WIDTH,  width)
        self._cap.set(cv2.CAP_PROP_FRAME_HEIGHT, height)
        self._cap.set(cv2.CAP_PROP_BUFFERSIZE, 1)  # Minimize buffer lag
        self._frame = None
        self._lock  = threading.Lock()
        self._running = True
        threading.Thread(target=self._capture_loop, daemon=True).start()
        print(f"Camera {index} started at {width}×{height}")

    def _capture_loop(self):
        while self._running:
            ret, frame = self._cap.read()
            if ret:
                with self._lock:
                    self._frame = frame

    def read(self):
        with self._lock:
            return self._frame.copy() if self._frame is not None else None

    def stop(self):
        self._running = False
        self._cap.release()


