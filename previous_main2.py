class SensorMonitor:
    """
    Monitors Ultrasonic (HC-SR04) and IR sensor in a background thread.
    Fires a callback when an obstacle is detected.
    """

    def __init__(self, tts: TTSSpeaker, cfg: dict):
        self.tts     = tts
        self.cfg     = cfg
        self.dist_cm = 999.0
        self.ir_triggered = False
        self._running = True

        if GPIO_AVAILABLE:
            try:
                self._ultrasonic = DistanceSensor(
                    echo    = cfg["ULTRASONIC_ECHO_PIN"],
                    trigger = cfg["ULTRASONIC_TRIGGER_PIN"],
                    max_distance = 4.0
                )
                self._ir = InputDevice(cfg["IR_SENSOR_PIN"])
            except Exception as e:
                print(f"Sensor init error: {e}")
                self._ultrasonic = None
                self._ir = None
        else:
            self._ultrasonic = None
            self._ir = None

        threading.Thread(target=self._monitor_loop, daemon=True).start()

    def _monitor_loop(self):
        while self._running:
            if self._ultrasonic:
                try:
                    self.dist_cm = self._ultrasonic.distance * 100.0
                    if self.dist_cm < self.cfg["OBSTACLE_WARN_CM"]:
                        self.tts.say(f"Warning. Obstacle at {int(self.dist_cm)} centimeters.")
                except Exception:
                    self.dist_cm = 999.0

            if self._ir:
                try:
                    self.ir_triggered = self._ir.is_active
                    if self.ir_triggered:
                        self.tts.say("Object very close. Stop.")
                except Exception:
                    self.ir_triggered = False

            time.sleep(0.2)  # Poll at 5 Hz

    def stop(self):
        self._running = False


