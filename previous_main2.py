class FaceEngine:
    """
    Loads pre-computed face encodings and recognizes faces in a frame.
    Falls back to Haar Cascade detect-only if face_recognition not available.
    """

    def __init__(self, encodings_file: str, tolerance: float = 0.50):
        self.tolerance = tolerance
        self.known_enc  = []
        self.known_names = []
        self._haar = cv2.CascadeClassifier(
            cv2.data.haarcascades + 'haarcascade_frontalface_default.xml'
        )

        if FACE_RECOGNITION_AVAILABLE and os.path.exists(encodings_file):
            with open(encodings_file, 'rb') as f:
                data = pickle.load(f)
            self.known_enc   = data["encodings"]
            self.known_names = data["names"]
            print(f"Loaded {len(self.known_enc)} face encoding(s) from '{encodings_file}'.")
        elif not os.path.exists(encodings_file):
            print(f"'{encodings_file}' not found. Running face detection only (no recognition).")
        else:
            print("face_recognition unavailable. Running Haar detection only.")

    def process(self, frame: np.ndarray):
        """
        Returns a list of (name, x, y, w, h) tuples for each face.
        name = person name if recognized, "Unknown" if detected but not matched.
        """
        results = []

        if FACE_RECOGNITION_AVAILABLE and self.known_enc:
            # Use face_recognition for identity matching
            # Resize to 1/2 for speed, then scale back
            small = cv2.resize(frame, (0, 0), fx=0.5, fy=0.5)
            rgb   = cv2.cvtColor(small, cv2.COLOR_BGR2RGB)
            locs  = face_recognition.face_locations(rgb, model="hog")
            encs  = face_recognition.face_encodings(rgb, locs)

            for enc, (top, right, bottom, left) in zip(encs, locs):
                name = "Unknown"
                if self.known_enc:
                    matches  = face_recognition.compare_faces(self.known_enc, enc, self.tolerance)
                    distances= face_recognition.face_distance(self.known_enc, enc)
                    best_idx = np.argmin(distances)
                    if matches[best_idx]:
                        name = self.known_names[best_idx]

                # Scale coordinates back to original size
                top    *= 2; right *= 2; bottom *= 2; left *= 2
                x, y, w, h = left, top, right - left, bottom - top
                results.append((name, x, y, w, h))

        else:
            # Haar Cascade only (detection, no recognition)
            gray  = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
            faces = self._haar.detectMultiScale(gray, scaleFactor=1.1, minNeighbors=4)
            for (x, y, w, h) in faces:
                results.append(("Person", x, y, w, h))

        return results


