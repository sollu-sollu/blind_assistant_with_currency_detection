import os  # needed for os.path.exists above

CURRENCY_LABELS = {
    "10_rupee":   "10 Rupees",
    "20_rupee":   "20 Rupees",
    "50_rupee":   "50 Rupees",
    "100_rupee":  "100 Rupees",
    "200_rupee":  "200 Rupees",
    "500_rupee":  "500 Rupees",
    "2000_rupee": "2000 Rupees",
}

# Labels from the general YOLO model that are useful for the blind
RELEVANT_OBJECTS = {
    "person", "car", "truck", "bus", "bicycle", "motorcycle",
    "chair", "door", "stairs", "bottle", "cup", "cell phone",
    "laptop", "tv", "book", "bag", "umbrella", "cat", "dog",
}


def draw_label(frame, text, x1, y1, color=(0, 255, 0)):
    cv2.rectangle(frame, (x1 - 1, y1 - 22), (x1 + len(text) * 9, y1), color, -1)
    cv2.putText(frame, text, (x1, y1 - 5),
                cv2.FONT_HERSHEY_SIMPLEX, 0.55, (0, 0, 0), 1, cv2.LINE_AA)


def main():
    print("\n" + "=" * 55)
    print("  BLIND ASSISTANT STARTING")
    print("=" * 55 + "\n")

    tts = TTSSpeaker(rate=CONFIG["SPEECH_RATE"], cooldown=CONFIG["TTS_COOLDOWN_S"])
    tts.say("Blind Assistant starting. Please wait.")

    # ── Models ──────────────────────────────────────────────────
    print("Loading YOLO26n general model...")
    general_model = YOLO(CONFIG["YOLO_GENERAL_MODEL"])

    # Auto-detect currency model: prefer NCNN (faster on Pi), fall back to .pt
    currency_model = None
    ncnn_path = CONFIG["YOLO_CURRENCY_MODEL_NCNN"]
    pt_path   = CONFIG["YOLO_CURRENCY_MODEL_PT"]

    if os.path.isdir(ncnn_path):
        print(f"Loading currency model (NCNN — fastest on Pi): {ncnn_path}")
        currency_model = YOLO(ncnn_path)
    elif os.path.exists(pt_path):
        print(f"Loading currency model (PyTorch): {pt_path}")
        currency_model = YOLO(pt_path)
    else:
        print("⚠ Currency model not found. Copy 'currency_yolo26n.pt' or")
        print("  'currency_yolo26n_ncnn_model/' folder to this directory.")
        print("  Object detection and face recognition will still work.")

    # ── Step 0: Auto-register faces before loading engine ────────
    # Detects new photos in known_faces/ and rebuilds face_encodings.pkl.
    # This happens automatically every time main2.py starts.
    auto_register_faces()

    # ── Face Engine ─────────────────────────────────────────────
    face_engine = FaceEngine(
        encodings_file=ENCODINGS_FILE,
        tolerance=CONFIG["FACE_TOLERANCE"]
    )

    # ── Camera ──────────────────────────────────────────────────
    cam = CameraStream(
        index  = CONFIG["CAMERA_INDEX"],
        width  = CONFIG["FRAME_WIDTH"],
        height = CONFIG["FRAME_HEIGHT"]
    )
    time.sleep(1.5)  # Let camera warm up

    # ── Sensors ──────────────────────────────────────────────────
    # Safe on Windows: GPIO_AVAILABLE=False so no pins are touched,
    # dist_cm stays 999 and ir_triggered stays False.
    sensors = SensorMonitor(tts, CONFIG)

    tts.say("System ready.")
    print("System ready. Press Q to quit.\n")

    frame_count          = 0
    fps_timer            = time.time()
    display_fps          = 0
    FACE_CHECK_EVERY     = CONFIG["FACE_CHECK_EVERY"]
    CURRENCY_CHECK_EVERY = CONFIG["CURRENCY_CHECK_EVERY"]

    while True:
        frame = cam.read()
        if frame is None:
            time.sleep(0.01)
            continue

        frame_count += 1

        # ── FPS Calculation ───────────────────────────────────
        if frame_count % 30 == 0:
            elapsed     = time.time() - fps_timer
            display_fps = 30 / elapsed if elapsed > 0 else 0
            fps_timer   = time.time()

        # ── STEP 1: YOLO26n General Object Detection ──────────
        results = general_model(
            frame,
            conf    = CONFIG["YOLO_CONF"],
            imgsz   = CONFIG["YOLO_IMGSZ"],
            verbose = False,
        )

        detected_currency_region = None
        person_detected          = False

        for r in results:
            for box in r.boxes:
                cls_id  = int(box.cls[0])
                label   = general_model.names[cls_id]
                conf    = float(box.conf[0])
                x1, y1, x2, y2 = map(int, box.xyxy[0])

                # Draw bounding box
                cv2.rectangle(frame, (x1, y1), (x2, y2), (0, 220, 0), 1)
                draw_label(frame, f"{label} {conf:.0%}", x1, y1, (0, 220, 0))

                # Trigger voice for relevant objects
                if label in RELEVANT_OBJECTS:
                    if label == "person":
                        person_detected = True
                        # Face recognition handled later
                    else:
                        tts.say(f"{label} ahead")

                # Flag currency region for the currency model
                if label in ("book", "paper") and currency_model:
                    detected_currency_region = (x1, y1, x2, y2)

        # ── STEP 2: Currency Recognition ─────────────────────
        # Run every CURRENCY_CHECK_EVERY frames to reduce Pi CPU load.
        if currency_model and (frame_count % CURRENCY_CHECK_EVERY == 0):
            currency_results = currency_model(
                frame,
                conf    = 0.60,   # Higher threshold — reduces false positives
                imgsz   = CONFIG["YOLO_IMGSZ"],
                verbose = False,
            )
            for r in currency_results:
                for box in r.boxes:
                    cls_id  = int(box.cls[0])
                    raw_lbl = currency_model.names[cls_id]
                    conf    = float(box.conf[0])
                    spoken  = CURRENCY_LABELS.get(raw_lbl, raw_lbl)
                    x1, y1, x2, y2 = map(int, box.xyxy[0])

                    cv2.rectangle(frame, (x1, y1), (x2, y2), (0, 215, 255), 2)
                    draw_label(frame, f"Rs {spoken}", x1, y1, (0, 200, 255))
                    tts.say(f"Currency detected. {spoken}.")

        # ── STEP 3: Face Recognition ──────────────────────────
        # Only runs every FACE_CHECK_EVERY frames to save CPU.
        # Triggered only when YOLO detected a person in this frame.
        if frame_count % FACE_CHECK_EVERY == 0 and person_detected:
            faces = face_engine.process(frame)
            for (name, x, y, w, h) in faces:
                color = (255, 80, 0) if name != "Unknown" else (80, 80, 255)
                cv2.rectangle(frame, (x, y), (x + w, y + h), color, 2)
                draw_label(frame, name, x, y, color)

                if name == "Unknown":
                    tts.say("Unknown person in front of you.")
                else:
                    tts.say(f"{name} is in front of you.")

        # ── STEP 4: Build HUD & Detection Panel ──────────────
        h_frame, w_frame = frame.shape[:2]

        # Top bar — FPS
        hud = f"FPS: {display_fps:.1f}   |   Press Q to quit"
        cv2.rectangle(frame, (0, 0), (w_frame, 24), (20, 20, 20), -1)
        cv2.putText(frame, hud, (8, 17),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.50, (180, 255, 180), 1, cv2.LINE_AA)

        # Right panel — detected objects + sensor data
        panel_lines = []

        # Sensor readings
        if GPIO_AVAILABLE and sensors._ultrasonic:
            dist_str = f"Dist: {sensors.dist_cm:.0f} cm"
            ir_str   = "IR: TRIGGERED!" if sensors.ir_triggered else "IR: Clear"
            panel_lines.append(dist_str)
            panel_lines.append(ir_str)
        else:
            panel_lines.append("Sensors: Offline (PC)")

        panel_lines.append("---")  # separator

        # YOLO detections
        for r in results:
            for box in r.boxes:
                lbl  = general_model.names[int(box.cls[0])]
                conf = float(box.conf[0])
                panel_lines.append(f"{lbl}  {conf:.0%}")

        pw = 185
        ph = len(panel_lines) * 20 + 32
        px = w_frame - pw - 4
        py = 30
        cv2.rectangle(frame, (px, py), (w_frame - 4, py + ph), (20, 20, 20), -1)
        cv2.putText(frame, "Status:", (px + 6, py + 16),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.45, (100, 255, 100), 1)
        for li, line in enumerate(panel_lines):
            # Color sensor lines differently
            if "Dist:" in line:
                color = (80, 220, 255)   # yellow-ish for distance
            elif "IR:" in line and "TRIGGERED" in line:
                color = (0, 80, 255)     # red for IR trigger
            elif "IR:" in line:
                color = (180, 255, 180)  # green for IR clear
            elif "---" in line:
                color = (80, 80, 80)     # grey separator
            else:
                color = (255, 255, 255)  # white for objects
            cv2.putText(frame, line, (px + 6, py + 32 + li * 20),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.42, color, 1)

        # Bottom legend bar
        legend = "Green=Object  Yellow=Currency  Blue=Person/Face"
        cv2.rectangle(frame, (0, h_frame - 20), (w_frame, h_frame), (20, 20, 20), -1)
        cv2.putText(frame, legend, (6, h_frame - 6),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.38, (180, 180, 180), 1, cv2.LINE_AA)

        # ── STEP 5: Show window ───────────────────────────────
        cv2.imshow("Blind Assistant — Detection View", frame)

        if cv2.waitKey(1) & 0xFF == ord('q'):
            break


    # ── Cleanup ───────────────────────────────────────────────
    cam.stop()
    sensors.stop()
    cv2.destroyAllWindows()
    print("Assistant stopped.")



if __name__ == "__main__":
    main()